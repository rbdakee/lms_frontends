#!/usr/bin/env bash
# Ignored Build Step для Vercel: коммит, задевший только админку, не должен
# пересобирать клиентское приложение.
#
# В настройках проекта (Settings → Git → Ignored Build Step):
#   bash ../../scripts/vercel-ignore.sh web
#   bash ../../scripts/vercel-ignore.sh admin
#
# Договорённость Vercel обратная привычной: выход 0 — сборку ПРОПУСТИТЬ,
# выход 1 — собирать. `git diff --quiet` отвечает ровно так же (0 — различий
# нет), поэтому проверка тут одна строка и никаких `if`.

set -u
app="${1:?нужно имя приложения: web или admin}"
cd "$(dirname "$0")/.." || exit 1

# База сравнения — последний УСПЕШНО выкаченный коммит этого проекта.
# `HEAD^` тут неверен: в пуше почти всегда несколько коммитов, и если
# последний задел только соседнее приложение, вместе с ним пропускались
# и все предыдущие. Так и вышло 21.08.2026: админка уехала, клиентское
# приложение осталось на позавчерашней сборке.
#
# `VERCEL_GIT_PREVIOUS_SHA` Vercel отдаёт только внутрь Ignored Build Step,
# и это ровно то, что нужно: у каждого проекта своя последняя удачная сборка.
base="${VERCEL_GIT_PREVIOUS_SHA:-}"

# Неизвестная база — первый деплой. Собираем.
[ -n "$base" ] || exit 1
# Клон неглубокий (--depth=10): база может не попасть в историю. Собираем.
git cat-file -e "$base^{commit}" 2>/dev/null || exit 1

# Общие пакеты и корневые файлы задевают оба приложения: правка кнопки
# в packages/ui обязана пересобрать и клиент, и админку
git diff --quiet "$base" HEAD -- \
  "apps/$app" \
  packages \
  package.json \
  package-lock.json \
  tsconfig.base.json
